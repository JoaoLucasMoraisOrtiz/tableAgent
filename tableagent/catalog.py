from typing import List, Dict


@dataclass
class Question:
    question_id: str
    text: str
    topic: str
    sql: str
    required_slots: List[str]
    category: str
    aliases: List[str] = None


class Catalog:
    def __init__(self, questions: List[Question]):
        self.questions = questions
        self.by_topic = {}
        self.by_id = {}
        
        for q in questions:
            if q.topic not in self.by_topic:
                self.by_topic[q.topic] = []
            self.by_topic[q.topic].append(q)
            self.by_id[q.question_id] = q


